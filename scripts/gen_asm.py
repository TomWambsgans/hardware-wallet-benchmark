"""Generate the device's Thumb-2 compression functions (ARMv8-M mainline, Cortex-M35P).

    python3 scripts/gen_asm.py   # writes ledger-app/src/crypto/{blake2s,sha256}_thumb2.S

What the Nano S Plus core rewards (measured with timing probes on the device):
  - 1 cycle per ALU op, rotate-immediate, load and store -- but only for code that stays
    in the ~2 KB instruction cache; straight-line code beyond that is fetch-bound at
    ~0.6 cycle per byte. So both functions are small loops, not unrolled.
  - 2 cycles for an operand with a rotate/shift (`eor r0, r1, r2, ror #7`): rotations
    are explicit `ror` instructions instead.
  - +1 cycle when a load is used by the next instruction: loads are issued early.
  - 1.5-2 cycles for loads from flash: tables are passed as pointers to RAM copies.
All functions are position independent and preserve r4-r11 and sp (tests/emu checks it).

BLAKE2s (blake2s_thumb2.S):
  void b2s_compress_asm(uint32_t h[8], const uint32_t m[16], uint32_t t, uint32_t f,
                        const uint8_t table[176])
  void b2s_oneblock16_asm(uint32_t out[4], const uint32_t block[16], uint32_t len,
                          const uint8_t table[176])   -- BLAKE2s-256(block[:len])[:16]
  A loop over the 10 rounds. Message word j of round r is at sp + table[16 r + j] (the
  message is copied to the stack; table = b2s_sigma_ofs, 4 * SIGMA, plus a sentinel row
  whose bit 7 ends the loop). State: a in r0-r3, b in r4-r7, d2/d3 in r8/r9; c0-c3 go
  through one slot register (r12) and d0/d1 through another (r10), leaving r11 for the
  table row pointer and lr for message words. The G order (column G1 G0 G2 G3, diagonal
  G1' G0' G2' G3') minimizes slot reloads (found by exhaustive search) and carries both
  slots across the loop edge.

SHA-256 (sha256_thumb2.S):
  void sha256_compress_asm(uint32_t h[8], const uint32_t block[16], const uint32_t k[65])
  void sha256_oneblock16_asm(uint32_t out[4], const uint32_t block[16], const uint32_t k[65])
      -- first 16 bytes (big-endian) of compress(IV, block)
  block is 64 bytes (read big-endian, `rev`); k = sha256_k, the 64 constants and a 0
  sentinel that ends the round loop. A schedule loop (two words an iteration) then a round
  loop (8 rounds an iteration, a..h renamed, Maj reusing the previous round's a ^ b).
"""

import pathlib
import random

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "ledger-app" / "src" / "crypto"

HEADER = """@ Generated by scripts/gen_asm.py -- do not edit.
    .syntax unified
    .thumb
    .text
"""


def mov32(reg: str, value: int) -> list[str]:
    """A 32-bit constant without a literal pool (position independent, no range limit)."""
    return [f"    movw {reg}, #{value & 0xFFFF:#06x}", f"    movt {reg}, #{value >> 16:#06x}"]


def function(name: str) -> list[str]:
    return [f"    .global {name}", f"    .type {name}, %function", "    .thumb_func", f"{name}:"]


