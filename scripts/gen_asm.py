# SHA-256

K256 = [
    0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
    0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
    0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
    0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
    0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
    0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
    0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
    0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
]
# Stack frame: W[0..63] at sp+0, h pointer at sp+256.
W_OFF, SHA_H_OFF, SHA_FRAME = 0, 256, 268  # 36 + 268: sp stays 8-aligned


def gen_sha256() -> str:
    out = [HEADER, "    .p2align 2", "sha256_k:"] + [f"    .word {k:#010x}" for k in K256]
    out += ["    .global sha256_compress_asm", "    .type sha256_compress_asm, %function", "    .thumb_func",
            "sha256_compress_asm:"]
    e = out.append
    e("    push {r4-r11, lr}")
    e("    adr lr, sha256_k")  # kept in lr through the schedule (which only uses r0-r3)
    e(f"    sub sp, sp, #{SHA_FRAME}")
    e(f"    str r0, [sp, #{SHA_H_OFF}]")
    # W[0..15] = m.
    e("    ldmia r1!, {r4-r11}")
    e("    stmia sp, {r4-r11}")
    e("    ldmia r1, {r4-r11}")
    e("    add r12, sp, #32")
    e("    stmia r12, {r4-r11}")
    # W[i] = sigma1(W[i-2]) + W[i-7] + sigma0(W[i-15]) + W[i-16], with
    # sigma0(x) = ROTR7(x) ^ ROTR18(x) ^ SHR3(x), sigma1(x) = ROTR17(x) ^ ROTR19(x) ^ SHR10(x).
    e("    @ message schedule")
    for i in range(16, 64):
        w = lambda j: f"[sp, #{W_OFF + 4 * j}]"  # noqa: E731
        e(f"    ldr r0, {w(i - 2)}")
        e(f"    ldr r1, {w(i - 15)}")
        e(f"    ldr r2, {w(i - 7)}")
        e(f"    ldr r3, {w(i - 16)}")
        e("    add r2, r2, r3")
        e("    ror r3, r0, #17")
        e("    eor r3, r3, r0, ror #19")
        e("    eor r3, r3, r0, lsr #10")
        e("    add r2, r2, r3")
        e("    ror r3, r1, #7")
        e("    eor r3, r3, r1, ror #18")
        e("    eor r3, r3, r1, lsr #3")
        e("    add r2, r2, r3")
        e(f"    str r2, {w(i)}")
    # Rounds: a..h in r4..r11 (renamed each round), K through r12, Maj's a^b in r2/lr.
    e("    @ rounds")
    e(f"    ldr r0, [sp, #{SHA_H_OFF}]")
    e("    ldm r0, {r4-r11}")
    e("    mov r12, lr")
    e("    eor lr, r5, r6")  # b ^ c for round 0's Maj
    regs = ["r4", "r5", "r6", "r7", "r8", "r9", "r10", "r11"]
    xprev, xcur = "lr", "r2"
    for i in range(64):
        a, b, c, d, ee, f, g, h = [regs[(j - i) % 8] for j in range(8)]
        e(f"    ldr r0, [r12], #4")
        e(f"    ldr r1, [sp, #{W_OFF + 4 * i}]")
        e(f"    add {h}, {h}, r0")
        e(f"    add {h}, {h}, r1")
        e(f"    eor r0, {f}, {g}")
        e(f"    and r0, r0, {ee}")
        e(f"    eor r0, r0, {g}")
        e(f"    add {h}, {h}, r0")
        e(f"    eor r0, {ee}, {ee}, ror #5")
        e(f"    eor r0, r0, {ee}, ror #19")
        e(f"    add {h}, {h}, r0, ror #6")
        e(f"    add {d}, {d}, {h}")
        e(f"    eor r0, {a}, {a}, ror #11")
        e(f"    eor r0, r0, {a}, ror #20")
        e(f"    add {h}, {h}, r0, ror #2")
        e(f"    eor {xcur}, {a}, {b}")
        e(f"    and r0, {xcur}, {xprev}")
        e(f"    eor r0, r0, {b}")
        e(f"    add {h}, {h}, r0")
        xprev, xcur = xcur, xprev
    # h[i] += state.
    e("    @ feed-forward")
    e(f"    ldr r12, [sp, #{SHA_H_OFF}]")
    e("    ldm r12, {r0-r3}")
    e("    add r0, r0, r4")
    e("    add r1, r1, r5")
    e("    add r2, r2, r6")
    e("    add r3, r3, r7")
    e("    stm r12!, {r0-r3}")
    e("    ldm r12, {r0-r3}")
    e("    add r0, r0, r8")
    e("    add r1, r1, r9")
    e("    add r2, r2, r10")
    e("    add r3, r3, r11")
    e("    stm r12, {r0-r3}")
    e(f"    add sp, sp, #{SHA_FRAME}")
    e("    pop {r4-r11, pc}")
    e("    .size sha256_compress_asm, . - sha256_compress_asm")
    return "\n".join(out) + "\n"


def gen_sha256_v2() -> str:
    """Same structure as gen_sha256, but no shifted operands: every rotation is an
    explicit `ror`, and the temporaries are low registers so most XORs and adds
    get 16-bit encodings."""
    out = [HEADER, "    .p2align 2", "sha256_k2:"] + [f"    .word {k:#010x}" for k in K256]
    out += ["    .global sha256_compress_asm2", "    .type sha256_compress_asm2, %function", "    .thumb_func",
            "sha256_compress_asm2:"]
    e = out.append
    e("    push {r4-r11, lr}")
    e("    adr lr, sha256_k2")
    e(f"    sub sp, sp, #{SHA_FRAME}")
    e(f"    str r0, [sp, #{SHA_H_OFF}]")
    e("    ldmia r1!, {r4-r11}")
    e("    stmia sp, {r4-r11}")
    e("    ldmia r1, {r4-r11}")
    e("    add r12, sp, #32")
    e("    stmia r12, {r4-r11}")
    e("    @ message schedule")
    for i in range(16, 64):
        w = lambda j: f"[sp, #{W_OFF + 4 * j}]"  # noqa: E731
        e(f"    ldr r0, {w(i - 2)}")
        e(f"    ldr r1, {w(i - 15)}")
        e(f"    ldr r2, {w(i - 7)}")
        e(f"    ldr r3, {w(i - 16)}")
        e("    adds r2, r2, r3")
        e("    ror r3, r0, #17")      # sigma1
        e("    ror r4, r0, #19")
        e("    eors r3, r4")
        e("    lsrs r0, r0, #10")
        e("    eors r3, r0")
        e("    adds r2, r2, r3")
        e("    ror r3, r1, #7")       # sigma0
        e("    ror r4, r1, #18")
        e("    eors r3, r4")
        e("    lsrs r1, r1, #3")
        e("    eors r3, r1")
        e("    adds r2, r2, r3")
        e(f"    str r2, {w(i)}")
    e("    @ rounds")
    e(f"    ldr r0, [sp, #{SHA_H_OFF}]")
    e("    ldm r0, {r4-r11}")
    e("    mov r12, lr")
    e("    eor lr, r5, r6")
    regs = ["r4", "r5", "r6", "r7", "r8", "r9", "r10", "r11"]
    xprev, xcur = "lr", "r2"
    for i in range(64):
        a, b, c, d, ee, f, g, h = [regs[(j - i) % 8] for j in range(8)]
        e("    ldr r0, [r12], #4")
        e(f"    ldr r1, [sp, #{W_OFF + 4 * i}]")
        e(f"    add {h}, r0")
        e(f"    add {h}, r1")
        e(f"    ror r0, {ee}, #6")     # Sigma1(e)
        e(f"    ror r1, {ee}, #11")
        e("    eors r0, r1")
        e(f"    ror r1, {ee}, #25")
        e("    eors r0, r1")
        e(f"    add {h}, r0")
        e(f"    eor r0, {f}, {g}")     # Ch(e, f, g)
        e(f"    and r0, r0, {ee}")
        e(f"    eor r0, r0, {g}")
        e(f"    add {h}, r0")
        e(f"    add {d}, {h}")
        e(f"    ror r0, {a}, #2")      # Sigma0(a)
        e(f"    ror r1, {a}, #13")
        e("    eors r0, r1")
        e(f"    ror r1, {a}, #22")
        e("    eors r0, r1")
        e(f"    add {h}, r0")
        e(f"    eor {xcur}, {a}, {b}")  # Maj(a, b, c)
        e(f"    and r0, {xcur}, {xprev}")
        e(f"    eor r0, r0, {b}")
        e(f"    add {h}, r0")
        xprev, xcur = xcur, xprev
    e("    @ feed-forward")
    e(f"    ldr r12, [sp, #{SHA_H_OFF}]")
    e("    ldm r12, {r0-r3}")
    e("    add r0, r4")
    e("    add r1, r5")
    e("    add r2, r6")
    e("    add r3, r7")
    e("    stm r12!, {r0-r3}")
    e("    ldm r12, {r0-r3}")
    e("    add r0, r8")
    e("    add r1, r9")
    e("    add r2, r10")
    e("    add r3, r11")
    e("    stm r12, {r0-r3}")
    e(f"    add sp, sp, #{SHA_FRAME}")
    e("    pop {r4-r11, pc}")
    e("    .size sha256_compress_asm2, . - sha256_compress_asm2")
    return "\n".join(out) + "\n"



# ---------------------------------------------------------------------------
# v3: compact loops that stay in the core's small instruction cache.
#
# Device probes (results/2026-09-24-probes.json) show a 1 KB loop body runs at
# 1 cycle per instruction while 4-8 KB of straight-line code is fetch-bound at
# ~0.6 cycles per byte; shifted operands cost 2 cycles; a load followed at once
# by its use stalls 1 cycle. So: loops, explicit rotations, loads scheduled early.

SIGP_OFF = 84  # BLAKE2s v3 frame: m at 0, c homes at 64, h pointer at 80, sigma row pointer at 84


def gen_blake2s_v3() -> str:
    """Round loop (10 iterations). Message word j of round r is at sp + SIGMA_OFS[r][j],
    read through a row pointer kept on the stack: three loads per word, issued a
    half-G ahead so none stalls. Column G0..G3 then diagonal G1', G3', G0', G2': the
    c word in r12 carries across both step boundaries and the loop edge (c0).
    The table has an 11th sentinel row (0x80): the next-round preload of the last
    round reads it, and its bit 7 ends the loop (flags survive: no flag-setting
    instruction follows the test)."""
    out = [HEADER, "    .p2align 2", "b2s_sigma_ofs:"]
    for r in range(10):
        out.append("    .byte " + ", ".join(str(4 * x) for x in SIGMA[r]))
    out.append("    .byte " + ", ".join(["0x80"] * 16))
    out += ["    .global b2s_compress_asm3", "    .type b2s_compress_asm3, %function", "    .thumb_func",
            "b2s_compress_asm3:"]
    e = out.append
    e("    push {r4-r11, lr}")
    e(f"    sub sp, sp, #{FRAME}")
    e(f"    str r0, [sp, #{H_OFF}]")
    e("    ldmia r1!, {r4-r11}")
    e("    stmia sp, {r4-r11}")
    e("    ldmia r1, {r4-r11}")
    e("    add r12, sp, #32")
    e("    stmia r12, {r4-r11}")
    out.extend(mov32("r8", B2S_IV[4]))
    e("    eor r8, r8, r2")
    out.extend(mov32("r9", B2S_IV[5]))
    out.extend(mov32("r10", B2S_IV[6]))
    e("    eor r10, r10, r3")
    out.extend(mov32("r11", B2S_IV[7]))
    for i in range(4):
        out.extend(mov32("r12", B2S_IV[i]))
        e(f"    str r12, [sp, #{C_OFF + 4 * i}]")
    e("    ldm r0, {r0-r7}")
    # Row pointer, first message word of round 0, c0 into the slot.
    e("    adr lr, b2s_sigma_ofs")
    e(f"    str lr, [sp, #{SIGP_OFF}]")
    e("    ldrb lr, [lr, #0]")
    e(f"    ldr r12, [sp, #{C_OFF}]")
    e("    ldr lr, [sp, lr]")
    e("1:")
    # (a, b, c, d, x byte index in the row, y byte index)
    cols = [(k, k, k, k, 2 * k, 2 * k + 1) for k in range(4)]
    diags = {k: (k, (k + 1) % 4, (k + 2) % 4, (k + 3) % 4, 8 + 2 * k, 9 + 2 * k) for k in range(4)}
    order = cols + [diags[1], diags[3], diags[0], diags[2]]
    assert [gg[2] for gg in order] == [0, 1, 2, 3, 3, 1, 2, 0]
    for n, (a, b, c, d, xj, yj) in enumerate(order):
        A, B, D = A_REG[a], B_REG[b], D_REG[d]
        last = n == len(order) - 1
        # lr holds this G's x word; r12 holds its c word.
        e(f"    add {A}, {B}")
        e(f"    add {A}, lr")
        e(f"    eor {D}, {D}, {A}")
        e(f"    ldr lr, [sp, #{SIGP_OFF}]")
        e(f"    ror {D}, {D}, #16")
        e(f"    ldrb lr, [lr, #{yj}]")
        e(f"    add r12, {D}")
        e("    ldr lr, [sp, lr]")
        e(f"    eor {B}, {B}, r12")
        e(f"    ror {B}, {B}, #12")
        e(f"    add {A}, {B}")
        e(f"    add {A}, lr")
        e(f"    eor {D}, {D}, {A}")
        if not last:
            nxt = order[n + 1]
            e(f"    ldr lr, [sp, #{SIGP_OFF}]")
            e(f"    ror {D}, {D}, #8")
            e(f"    ldrb lr, [lr, #{nxt[4]}]")
            e(f"    add r12, {D}")
            e("    ldr lr, [sp, lr]")
            e(f"    eor {B}, {B}, r12")
            e(f"    ror {B}, {B}, #7")
            if nxt[2] != c:
                e(f"    str r12, [sp, #{C_OFF + 4 * c}]")
                e(f"    ldr r12, [sp, #{C_OFF + 4 * nxt[2]}]")
        else:
            # Advance the row pointer, preload next round's first word, test the sentinel.
            e(f"    ldr lr, [sp, #{SIGP_OFF}]")
            e(f"    ror {D}, {D}, #8")
            e("    add lr, lr, #16")
            e(f"    add r12, {D}")
            e(f"    str lr, [sp, #{SIGP_OFF}]")
            e(f"    ldrb lr, [lr, #{order[0][4]}]")
            e(f"    eor {B}, {B}, r12")
            e("    tst lr, #0x80")
            e("    ldr lr, [sp, lr]")
            e(f"    ror {B}, {B}, #7")
            e("    beq 1b")
    # r12 holds c0 (dirty).
    e("    @ finalization")
    e(f"    str r12, [sp, #{C_OFF}]")
    e(f"    ldr lr, [sp, #{H_OFF}]")
    for i in range(4):
        e(f"    ldr r12, [sp, #{C_OFF + 4 * i}]")
        e(f"    eor {A_REG[i]}, {A_REG[i]}, r12")
        e(f"    ldr r12, [lr, #{4 * i}]")
        e(f"    eor {A_REG[i]}, {A_REG[i]}, r12")
        e(f"    str {A_REG[i]}, [lr, #{4 * i}]")
    for i in range(4):
        e(f"    ldr r12, [lr, #{16 + 4 * i}]")
        e(f"    eor r12, r12, {B_REG[i]}")
        e(f"    eor r12, r12, {D_REG[i]}")
        e(f"    str r12, [lr, #{16 + 4 * i}]")
    e(f"    add sp, sp, #{FRAME}")
    e("    pop {r4-r11, pc}")
    e("    .size b2s_compress_asm3, . - b2s_compress_asm3")
    return "\n".join(out) + "\n"


def gen_sha256_v3() -> str:
    """Schedule loop (two words per iteration, W[i-2], W[i-1], W[i-16] carried in
    fixed registers) then round loop (8 rounds per iteration with a..h renamed;
    ends when the next K is the 0 sentinel after the table)."""
    out = [HEADER, "    .p2align 2", "sha256_k3:"] + [f"    .word {k:#010x}" for k in K256] + ["    .word 0"]
    out += ["    .global sha256_compress_asm3", "    .type sha256_compress_asm3, %function", "    .thumb_func",
            "sha256_compress_asm3:"]
    e = out.append
    e("    push {r4-r11, lr}")
    e(f"    sub sp, sp, #{SHA_FRAME}")
    e(f"    str r0, [sp, #{SHA_H_OFF}]")
    e("    ldmia r1!, {r4-r11}")
    e("    stmia sp, {r4-r11}")
    e("    ldmia r1, {r4-r11}")
    e("    add r12, sp, #32")
    e("    stmia r12, {r4-r11}")
    # Schedule: rA = W[i-2], rB = W[i-1], rC = W[i-16]; p = &W[i] (r12), pend = &W[64] (lr).
    rA, rB, rC, t, u = "r8", "r9", "r10", "r4", "r5"
    e(f"    ldr {rA}, [sp, #{4 * 14}]")
    e(f"    ldr {rB}, [sp, #{4 * 15}]")
    e(f"    ldr {rC}, [sp, #0]")
    e("    add r12, sp, #64")
    e("    add lr, sp, #256")
    e("2:")
    e("    ldr r0, [r12, #-60]")       # W[i-15]
    e("    ldr r2, [r12, #-28]")       # W[i-7]
    e("    ldr r3, [r12, #-24]")       # W[i-6]
    e(f"    ror {t}, {rA}, #17")        # sigma1(W[i-2])
    e(f"    ror {u}, {rA}, #19")
    e(f"    eor {t}, {u}")
    e(f"    lsr {u}, {rA}, #10")
    e(f"    eor {t}, {u}")
    e(f"    add {rA}, {t}, r2")
    e(f"    add {rA}, {rC}")
    e(f"    ldr {rC}, [r12, #-56]")     # W[i-14]: sigma0 input of W[i+1], and W[i-16] of the next pair
    e(f"    ror {t}, r0, #7")           # sigma0(W[i-15])
    e(f"    ror {u}, r0, #18")
    e(f"    eor {t}, {u}")
    e(f"    lsr {u}, r0, #3")
    e(f"    eor {t}, {u}")
    e(f"    add {rA}, {t}")
    e(f"    str {rA}, [r12], #4")       # W[i]
    e(f"    ror {t}, {rB}, #17")        # sigma1(W[i-1])
    e(f"    ror {u}, {rB}, #19")
    e(f"    eor {t}, {u}")
    e(f"    lsr {u}, {rB}, #10")
    e(f"    eor {t}, {u}")
    e(f"    add {rB}, {t}, r3")
    e(f"    add {rB}, r0")
    e(f"    ror {t}, {rC}, #7")         # sigma0(W[i-14])
    e(f"    ror {u}, {rC}, #18")
    e(f"    eor {t}, {u}")
    e(f"    lsr {u}, {rC}, #3")
    e(f"    eor {t}, {u}")
    e(f"    add {rB}, {t}")
    e(f"    str {rB}, [r12], #4")       # W[i+1]
    e("    cmp r12, lr")
    e("    bne 2b")
    # Rounds: a..h in r4..r11, K via r12, W via r3, Maj's a^b in r2/lr.
    e(f"    ldr r0, [sp, #{SHA_H_OFF}]")
    e("    ldm r0, {r4-r11}")
    e("    adr r12, sha256_k3")
    e("    mov r3, sp")
    e("    eor lr, r5, r6")
    e("3:")
    regs = ["r4", "r5", "r6", "r7", "r8", "r9", "r10", "r11"]
    xprev, xcur = "lr", "r2"
    for i in range(8):
        a, b, c, d, ee, f, g, h = [regs[(j - i) % 8] for j in range(8)]
        e("    ldr r0, [r12], #4")
        e("    ldr r1, [r3], #4")
        e(f"    add {h}, r0")
        e(f"    add {h}, r1")
        e(f"    ror r0, {ee}, #6")
        e(f"    ror r1, {ee}, #11")
        e("    eor r0, r1")
        e(f"    ror r1, {ee}, #25")
        e("    eor r0, r1")
        e(f"    add {h}, r0")
        e(f"    eor r0, {f}, {g}")
        e(f"    and r0, {ee}")
        e(f"    eor r0, {g}")
        e(f"    add {h}, r0")
        e(f"    add {d}, {h}")
        e(f"    ror r0, {a}, #2")
        e(f"    ror r1, {a}, #13")
        e("    eor r0, r1")
        e(f"    ror r1, {a}, #22")
        e("    eor r0, r1")
        e(f"    add {h}, r0")
        if i == 7:
            e("    ldr r1, [r12]")       # peek the next K (0 after the table)
        e(f"    eor {xcur}, {a}, {b}")
        e(f"    and r0, {xcur}, {xprev}")
        e(f"    eor r0, {b}")
        e(f"    add {h}, r0")
        xprev, xcur = xcur, xprev
    e("    cmp r1, #0")
    e("    bne 3b")
    e("    @ feed-forward")
    e(f"    ldr r12, [sp, #{SHA_H_OFF}]")
    e("    ldm r12, {r0-r3}")
    e("    add r0, r4")
    e("    add r1, r5")
    e("    add r2, r6")
    e("    add r3, r7")
    e("    stm r12!, {r0-r3}")
    e("    ldm r12, {r0-r3}")
    e("    add r0, r8")
    e("    add r1, r9")
    e("    add r2, r10")
    e("    add r3, r11")
    e("    stm r12, {r0-r3}")
    e(f"    add sp, sp, #{SHA_FRAME}")
    e("    pop {r4-r11, pc}")
    e("    .size sha256_compress_asm3, . - sha256_compress_asm3")
    return "\n".join(out) + "\n"

