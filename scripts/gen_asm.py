def gen_probes() -> tuple[str, str]:
    out = [HEADER]
    e = out.append
    for k, (name, body, reps, plus2, reset) in enumerate(PROBES):
        e(f"    @ probe {k}: {name}")
        e(f"    .global probe_{k}")
        e(f"    .type probe_{k}, %function")
        e("    .p2align 3")
        e("    .thumb_func")
        e(f"probe_{k}:")
        e("    push {r4-r11, lr}")
        e("    mov r12, r1")
        e("    movs r2, #1")
        e("    movs r3, #3")
        e("    movs r4, #5")
        e("    movs r5, #7")
        e("    b 2f")
        e("    .p2align 3")
        if plus2:
            e("    nop")
        e("2:")
        if reset:
            e("    mov r12, r1")
        e(f"    .rept {reps}")
        out.extend(f"    {line}" for line in body)
        e("    .endr")
        e("    subs r0, r0, #1")
        e("    bne 2b")
        e("    pop {r4-r11, pc}")
        e(f"    .size probe_{k}, . - probe_{k}")
    c = ["// Generated by scripts/gen_asm.py -- do not edit.", "#include \"probes.h\"", ""]
    c += [f"void probe_{k}(uint32_t iterations, uint32_t *buf);" for k in range(len(PROBES))]
    c += ["", "const uint8_t PROBE_COUNT = " + str(len(PROBES)) + ";", "",
          "// Instructions per loop iteration of each probe (body + subs + bne, + reset).",
          "uint32_t probe_insns(unsigned id) {", "    switch (id) {"]
    for k, (name, body, reps, plus2, reset) in enumerate(PROBES):
        c.append(f"        case {k}: return {len(body) * reps + 2 + int(reset)};  // {name}")
    c += ["        default: return 0;", "    }", "}", "",
          "void run_probe(unsigned id, uint32_t iterations, uint32_t *buf) {", "    switch (id) {"]
    for k in range(len(PROBES)):
        c.append(f"        case {k}: probe_{k}(iterations, buf); break;")
    c += ["        default: break;", "    }", "}", ""]
    return "\n".join(out) + "\n", "\n".join(c)


