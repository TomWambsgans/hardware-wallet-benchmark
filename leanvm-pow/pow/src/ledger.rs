//! The host's side of verifying on a Ledger: the program data the device verifier compiles in, and the proof as
//! the byte stream it reads (`ledger/verifier`).

use std::collections::BTreeSet;
use std::fmt::Write as _;

use leanvm_core::cpu::{Program, Proof, bytecode_table, public_input_bytes};
use leanvm_ledger_verifier::transcript::{Piece, Source};
use leanvm_ledger_verifier::{Error, verify};
use primitives::field::F192;
use sha3::{Digest as _, Keccak256};

/// leanVM's Keccak-relation label (`crates/verifier/src/layout.rs`), part of every transcript's IV.
const RELATION_LABEL: &[u8] = b"leanVM keccak GKR: keccak-f in two cell layouts, depth 12, packs of 16 in degree 23, lane slots then table columns, output claimed by the bus";

/// `ledger/verifier/src/program.rs` for `program`: the stacked bytecode table, sparse, and the Fiat-Shamir IV.
pub fn program_data(program: &Program, description: &str) -> String {
    let table: Vec<u64> = bytecode_table(&program.prog).iter().map(|word| word.0).collect();
    assert!(table.len().is_power_of_two());
    let log_len = table.len().trailing_zeros() as usize;
    let rows = table.len() / 16;
    assert!(rows <= 1 << 16, "a row index must fit 16 bits");

    // The IV: keccak("leanvm" | len(relation) | relation | keccak(table)), as leanVM's `Bytecode::new`.
    let table_bytes: Vec<u8> = table.iter().flat_map(|word| word.to_le_bytes()).collect();
    let bytecode_hash = Keccak256::digest(&table_bytes);
    let relation = Keccak256::digest(RELATION_LABEL);
    let mut preimage = b"leanvm".to_vec();
    preimage.extend((relation.len() as u64).to_le_bytes());
    preimage.extend(relation);
    preimage.extend(bytecode_hash);
    let iv = Keccak256::digest(&preimage);

    let dict: Vec<u64> = table
        .iter()
        .copied()
        .filter(|&w| w != 0)
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect();
    assert!(dict.len() < 1 << 16);
    let mut entries = Vec::new();
    let mut starts = vec![0usize];
    for column in 0..16 {
        for row in 0..rows {
            let word = table[column * rows + row];
            if word != 0 {
                let index = dict.binary_search(&word).unwrap();
                entries.push((row as u32) << 16 | index as u32);
            }
        }
        starts.push(entries.len());
    }

    let mut out = String::new();
    writeln!(
        out,
        "//! Generated by `keccak-pow --gen-ledger` from {description}. Do not edit."
    )
    .unwrap();
    writeln!(out, "//!").unwrap();
    writeln!(
        out,
        "//! The stacked bytecode table ({} words, {} of them nonzero, {} distinct), as per-column",
        table.len(),
        entries.len(),
        dict.len()
    )
    .unwrap();
    writeln!(
        out,
        "//! entries `row << 16 | dictionary index`, and the Fiat-Shamir IV it gives every transcript."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "pub const LOG_LEN: usize = {log_len};").unwrap();
    writeln!(out, "pub const FIAT_SHAMIR_IV: [u8; 32] = {:?};", iv.as_slice()).unwrap();
    writeln!(out, "pub static COLUMN_START: [u32; 17] = {starts:?};").unwrap();
    write!(out, "pub static DICT: [u64; {}] = [", dict.len()).unwrap();
    for (i, word) in dict.iter().enumerate() {
        if i % 6 == 0 {
            out.push_str("\n   ");
        }
        write!(out, " {word:#018x},").unwrap();
    }
    out.push_str("\n];\n");
    write!(out, "pub static ENTRIES: [u32; {}] = [", entries.len()).unwrap();
    for (i, entry) in entries.iter().enumerate() {
        if i % 10 == 0 {
            out.push_str("\n   ");
        }
        write!(out, " {entry:#010x},").unwrap();
    }
    out.push_str("\n];\n");
    out
}

/// A leanVM proof served piece by piece, in the order the device verifier asks, every byte recorded: the
/// recording is the stream the device reads.
pub struct Recorder<'a> {
    proof: &'a Proof,
    scalar: usize,
    batch: Option<usize>,
    row: usize,
    sibling: usize,
    pub bytes: Vec<u8>,
}

impl<'a> Recorder<'a> {
    pub fn new(proof: &'a Proof) -> Self {
        Self {
            proof,
            scalar: 0,
            batch: None,
            row: 0,
            sibling: 0,
            bytes: Vec::new(),
        }
    }
}

impl Source for Recorder<'_> {
    fn read(&mut self, piece: Piece, out: &mut [u8]) -> Result<(), Error> {
        match piece {
            Piece::Scalar => {
                let value: F192 = *self.proof.stream.get(self.scalar).ok_or(Error::StreamExhausted)?;
                self.scalar += 1;
                for (chunk, limb) in out.chunks_mut(8).zip([value.c0, value.c1, value.c2]) {
                    chunk.copy_from_slice(&limb.to_le_bytes());
                }
            }
            Piece::Batch => {
                let next = self.batch.map_or(0, |b| b + 1);
                let batch = self.proof.merkle.get(next).ok_or(Error::StreamExhausted)?;
                if let Some(previous) = self.batch {
                    let previous = &self.proof.merkle[previous];
                    if self.row != previous.leaf_data.len() || self.sibling != previous.sibling_hashes.len() {
                        return Err(Error::StreamNotConsumed);
                    }
                }
                let _ = batch;
                self.batch = Some(next);
                (self.row, self.sibling) = (0, 0);
            }
            Piece::Row => {
                let batch = &self.proof.merkle[self.batch.ok_or(Error::StreamExhausted)?];
                let row = batch.leaf_data.get(self.row).ok_or(Error::StreamExhausted)?;
                if out.len() != 8 * row.len() {
                    return Err(Error::Transport);
                }
                self.row += 1;
                for (chunk, word) in out.chunks_mut(8).zip(row) {
                    chunk.copy_from_slice(&word.0.to_le_bytes());
                }
            }
            Piece::Sibling => {
                let batch = &self.proof.merkle[self.batch.ok_or(Error::StreamExhausted)?];
                let sibling = batch.sibling_hashes.get(self.sibling).ok_or(Error::StreamExhausted)?;
                self.sibling += 1;
                out.copy_from_slice(sibling);
            }
        }
        self.bytes.extend_from_slice(out);
        Ok(())
    }

    fn finish(&mut self) -> Result<(), Error> {
        let batches = self.batch.map_or(0, |b| b + 1);
        let last_done = self.batch.is_none_or(|b| {
            let batch = &self.proof.merkle[b];
            self.row == batch.leaf_data.len() && self.sibling == batch.sibling_hashes.len()
        });
        if self.scalar == self.proof.stream.len() && batches == self.proof.merkle.len() && last_done {
            Ok(())
        } else {
            Err(Error::StreamNotConsumed)
        }
    }
}

/// The recorded stream, read back as the device reads it.
pub struct Bytes<'a> {
    pub data: &'a [u8],
    pub at: usize,
}

impl Source for Bytes<'_> {
    fn read(&mut self, _: Piece, out: &mut [u8]) -> Result<(), Error> {
        let end = self.at + out.len();
        out.copy_from_slice(self.data.get(self.at..end).ok_or(Error::StreamExhausted)?);
        self.at = end;
        Ok(())
    }

    fn finish(&mut self) -> Result<(), Error> {
        if self.at == self.data.len() {
            Ok(())
        } else {
            Err(Error::StreamNotConsumed)
        }
    }
}

/// Verify `proof` with the device verifier, natively; on success, the byte stream the device reads.
pub fn device_stream(proof: &Proof, public_input: &[F192; 2]) -> Result<Vec<u8>, Error> {
    let statement = public_input_bytes(public_input);
    let mut recorder = Recorder::new(proof);
    verify(&statement, &mut recorder)?;
    let bytes = recorder.bytes;
    verify(&statement, &mut Bytes { data: &bytes, at: 0 })?;
    Ok(bytes)
}

/// Check the device verifier on a recorded stream (the public input, then the proof): it accepts it, and rejects
/// every one of `flips` single-bit corruptions spread over the whole stream, and a changed public input. Returns
/// how many corruptions it rejected.
pub fn tamper_check(recorded: &[u8], flips: usize) -> Result<usize, String> {
    let (statement, stream) = recorded.split_at(32);
    let statement: [u8; 32] = statement.try_into().unwrap();
    verify(&statement, &mut Bytes { data: stream, at: 0 }).map_err(|e| format!("rejects the honest stream: {e:?}"))?;
    let mut bad_statement = statement;
    bad_statement[0] ^= 1;
    if verify(&bad_statement, &mut Bytes { data: stream, at: 0 }).is_ok() {
        return Err("accepts a changed public input".into());
    }
    let mut rejected = 0;
    let mut copy = stream.to_vec();
    for k in 0..flips {
        // Evenly spread, each at a different bit of its byte.
        let at = k * stream.len() / flips + k % 7;
        let bit = 1u8 << (k % 8);
        copy[at] ^= bit;
        match verify(&statement, &mut Bytes { data: &copy, at: 0 }) {
            Ok(()) => return Err(format!("accepts a corruption at byte {at} (bit {})", k % 8)),
            Err(_) => rejected += 1,
        }
        copy[at] ^= bit;
    }
    Ok(rejected)
}
